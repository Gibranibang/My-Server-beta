export type I18nKey = keyof (typeof I18N)["en"]

/**
 * Graceful Fallback Chain:
 * 1. Checks requested language dictionary
 * 2. Falls back to English (Default)
 * 3. Falls back to provided fallbackText
 * 4. Falls back to the key name itself
 * Guaranteed to NEVER return undefined.
 */
export function getTranslation(lang?: string): (key: I18nKey | string, fallbackText?: string) => string {
  const code: Language = lang === "id" ? "id" : "en"
  return (key: I18nKey | string, fallbackText?: string) => {
    return (I18N[code] as Record<string, string>)?.[key as string] || (I18N["en"] as Record<string, string>)?.[key as string] || fallbackText || (key as string)
  }
}
